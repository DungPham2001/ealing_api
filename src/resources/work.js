/** 3.6 Work: Queue (Kanban) and tasks. */
const { define } = require('../core/registry');
const f = require('../core/fields');
const { E } = require('../models/enums');
const { diffDays } = require('../lib/dates');

const { R } = f;
const S = (o) => f.str(120, o);

const ref = () => f.obj({ resource: f.str(40, { required: true, pii: false }), id: f.str(64, { pii: false }), code: f.str(40, { required: true, pii: false }) });

define({
  path: 'queue-items', prefix: 'Q', noun: 'mục hàng đợi', statusField: 'status', searchFields: ['title', 'type', 'assigneeName'],
  fields: {
    type: f.en(E.QUEUE_TYPE, { required: true, default: 'manual' }),
    source: f.obj({ resource: f.str(40, { required: true, pii: false }), id: f.str(64, { required: true, pii: false }), code: f.str(40, { required: true, pii: false }) }, { readOnly: true }),
    title: S(R),
    priority: f.en(E.PRIORITY, { required: true, default: 'normal' }),
    enqueuedAt: f.str(30, { readOnly: true, pii: false }),
    targetDueAt: f.date(),
    assigneeName: f.str(40),
    status: f.en(E.QUEUE_STATUS, { required: true, default: 'waiting' }),
    autoGenerated: f.bool({ readOnly: true }),
  },
  indexes: [[{ 'source.id': 1, type: 1 }, { unique: true, partialFilterExpression: { autoGenerated: true } }], [{ 'source.id': 1 }]],
  prepare(m, existing) {
    if (!existing) m.enqueuedAt = new Date().toISOString().replace(/\.\d{3}Z$/, 'Z');
  },
  computed: {
    waitDays: (i, c, d, env) => {
      const from = d.enqueuedAt?.slice(0, 10);
      const to = d.status === 'done' && d.updatedAt ? new Date(d.updatedAt).toISOString().slice(0, 10) : env.today;
      return from ? Math.max(0, diffDays(from, to)) : 0;
    },
    isOverdue: (i, c, d, env) => !!d.targetDueAt && d.status !== 'done' && d.targetDueAt < env.today,
  },
});

define({
  path: 'tasks', prefix: 'CV', noun: 'việc cần làm', statusField: 'status', searchFields: ['title', 'priority'],
  fields: {
    title: S(R),
    relatedRef: ref(),
    dueDate: f.date(),
    priority: f.en(E.PRIORITY, { required: true, default: 'normal' }),
    status: f.en(E.TASK_STATUS, { required: true, default: 'todo' }),
    remindBeforeDays: f.int({ max: 365 }),
  },
  computed: { isOverdue: (i, c, d, env) => !!d.dueDate && d.status !== 'done' && d.dueDate < env.today },
});
