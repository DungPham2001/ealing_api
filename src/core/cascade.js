/**
 * Delete rules (spec section 5), driven by each ref field's `onDelete`:
 *   cascade  -> children are deleted too (and their own children)
 *   unlink   -> the child's field becomes null (children matching `purge` are deleted instead)
 *   restrict -> deletion is refused (409 has_dependents) while children exist
 *   none     -> ignored
 * Children point at the parent by `code` (units: code + the property code in `via`).
 * Queue items generated from a deleted record go too; Scenario targets are unlinked, the scenario is kept.
 */
const registry = require('./registry');
const { conflict } = require('../utils/AppError');

const childLinks = (path) => registry.all().flatMap((cfg) => cfg.refs.filter((r) => r.to === path).map((r) => ({ cfg, ...r })));

const parentMatch = (link, docs) => {
  if (link.via) return { $or: docs.map((d) => ({ [link.name]: d.code, [link.via]: d[link.via] })) };
  return { [link.name]: { $in: docs.map((d) => d.code) } };
};

/** What deleting `docs` of `path` does. */
async function plan(path, docs, session) {
  const cfg0 = registry.get(path);
  const roots = cfg0.siblings ? await cfg0.siblings(docs, session) : docs;
  const removed = new Map([[path, new Map(roots.map((d) => [String(d._id), d]))]]);
  const unlinks = [];
  const blocked = [];
  const queue = [[path, roots]];
  while (queue.length) {
    const [p, batch] = queue.shift();
    for (const link of childLinks(p)) {
      if (link.onDelete === 'none') continue;
      const rows = await link.cfg.Model.find(parentMatch(link, batch)).session(session).lean();
      const gone = removed.get(link.cfg.path);
      const fresh = rows.filter((r) => !gone?.has(String(r._id)));
      if (!fresh.length) continue;
      if (link.onDelete === 'restrict') {
        blocked.push({ resource: link.cfg.path, field: link.name, count: fresh.length });
        continue;
      }
      let del = fresh;
      if (link.onDelete === 'unlink') {
        const purged = link.purge ? fresh.filter((r) => Object.entries(link.purge).every(([k, v]) => r[k] === v)) : [];
        const pset = new Set(purged.map((r) => String(r._id)));
        const rest = fresh.filter((r) => !pset.has(String(r._id)));
        if (rest.length) unlinks.push({ cfg: link.cfg, field: link.name, ids: rest.map((r) => String(r._id)) });
        del = purged;
      }
      if (!del.length) continue;
      if (!removed.has(link.cfg.path)) removed.set(link.cfg.path, new Map());
      for (const r of del) removed.get(link.cfg.path).set(String(r._id), r);
      queue.push([link.cfg.path, del]);
    }
  }
  return { removed, unlinks, blocked };
}

/** Summary for DELETE preview: { willDelete: { units: 24 }, willUnlink: {...}, blockedBy: [...] } (keys camelCase). */
function impact(p, rootPath) {
  const camel = (s) => s.replace(/-(\w)/g, (_, c) => c.toUpperCase());
  const willDelete = {};
  for (const [path, m] of p.removed) if (path !== rootPath || m.size > 1) willDelete[camel(path)] = path === rootPath ? m.size - 1 : m.size;
  const willUnlink = {};
  for (const u of p.unlinks) willUnlink[camel(u.cfg.path)] = (willUnlink[camel(u.cfg.path)] || 0) + u.ids.length;
  return { willDelete, willUnlink, blockedBy: p.blocked.map((b) => ({ resource: b.resource, field: b.field, count: b.count })) };
}

const SCENARIO_KIND = { deals: 'deal', 'development-projects': 'development_project', 'exit-plans': 'exit_plan' };

async function execute(p, session) {
  const live = (path, id) => !p.removed.get(path)?.has(id);
  for (const { cfg, field, ids } of p.unlinks) {
    const keep = ids.filter((id) => live(cfg.path, id));
    if (keep.length) await cfg.Model.updateMany({ _id: { $in: keep } }, { $set: { [field]: null }, $inc: { version: 1 } }, { session });
  }
  const allIds = [];
  for (const [path, m] of p.removed) {
    await registry.get(path).Model.deleteMany({ _id: { $in: [...m.keys()] } }, { session });
    allIds.push(...m.keys());
    const kind = SCENARIO_KIND[path];
    if (kind) {
      const codes = [...m.values()].map((d) => d.code);
      const S = registry.get('scenarios');
      if (S) await S.Model.updateMany({ 'target.kind': kind, 'target.code': { $in: codes } }, { $set: { target: null }, $inc: { version: 1 } }, { session });
    }
  }
  const Q = registry.get('queue-items');
  if (Q && allIds.length) await Q.Model.deleteMany({ autoGenerated: true, 'source.id': { $in: allIds } }, { session });
}

function assertNotBlocked(p) {
  if (p.blocked.length) {
    throw conflict('has_dependents', 'Không thể xóa: còn bản ghi phụ thuộc', { blockedBy: p.blocked });
  }
}

module.exports = { plan, execute, impact, assertNotBlocked };
