/**
 * Server-generated Queue items (spec section 6). For each source record: the condition holds and no auto item exists for
 * (source id, type) -> create one (waiting); it exists as done and the condition holds again -> reopen to waiting;
 * the condition no longer holds -> the auto item becomes done. Runs after every write to a source record and from the
 * daily job for the time-driven conditions. Manual items are never touched.
 */
const registry = require('../core/registry');
const { addDays, diffDays, monthEnd } = require('../lib/dates');
const { leaseStatus } = require('./calc');

const cut = (s) => String(s).slice(0, 120);
const prio = (days) => (days <= 14 ? 'urgent' : days <= 45 ? 'high' : 'normal');

/** source resource -> { type, rule(doc, env) -> { title, priority, targetDueAt } | null } */
const RULES = {
  leases: {
    type: 'lease_renewal',
    rule: (d, env) => (leaseStatus(d, env) === 'expiring'
      ? { title: `Gia hạn hợp đồng ${d.code} (${d.propertyCode}/${d.unitCode})`, priority: prio(diffDays(env.today, d.endDate)), targetDueAt: addDays(d.endDate, -14) } : null),
  },
  units: {
    type: 'vacant_unit',
    rule: (d, env) => {
      if (d.status !== 'vacant') return null;
      const days = d.vacantSince ? diffDays(d.vacantSince, env.today) : 0;
      return { title: `Đơn vị trống ${d.propertyCode}/${d.unitCode}`, priority: days > 60 ? 'urgent' : days > 30 ? 'high' : 'normal', targetDueAt: addDays(env.today, 7) };
    },
  },
  loans: {
    type: 'loan_maturity',
    rule: (d, env) => (d.refinanceNote || (d.currentBalance && d.currentBalance.amountMinor === 0) || diffDays(env.today, d.maturityDate) > env.settings.loanMaturityMonths * 30.4375
      ? null : { title: `Phương án tái tài trợ — ${d.lenderName}`, priority: 'high', targetDueAt: addDays(d.maturityDate, -90) }),
  },
  'work-orders': {
    type: 'maintenance',
    rule: (d) => (d.status === 'new' && !d.vendorCode ? { title: `Giao nhà thầu: ${d.title}`, priority: d.priority, targetDueAt: d.dueDate || null } : null),
  },
  equipment: {
    type: 'warranty_expiring',
    rule: (d, env) => (d.warrantyEnd && d.warrantyEnd >= env.today && diffDays(env.today, d.warrantyEnd) <= env.settings.warrantyExpiringDays
      ? { title: `Bảo hành sắp hết: ${d.kind} ${d.propertyCode}`, priority: 'normal', targetDueAt: d.warrantyEnd } : null),
  },
  'pm-schedules': {
    type: 'pm_due',
    rule: (d, env) => (['due', 'overdue'].includes(d.status) ? { title: `Bảo trì định kỳ: ${d.task}`, priority: d.status === 'overdue' ? 'high' : 'normal', targetDueAt: d.nextDueAt } : null),
  },
  utilities: {
    type: 'maintenance',
    rule: (d) => (d.status === 'abnormal_rise' ? { title: `Kiểm tra rò rỉ/thiết bị: ${d.kind} ${d.propertyCode} ${d.period}`, priority: 'normal', targetDueAt: null } : null),
  },
  'month-end-closes': {
    type: 'closing',
    rule: (d, env) => (!['done', 'locked'].includes(d.status) && env.today >= addDays(monthEnd(`${d.month}-01`), -env.settings.closeWarnDays)
      ? { title: `Đóng sổ ${d.entityCode} ${d.month}`, priority: 'high', targetDueAt: d.dueDate } : null),
  },
  deals: {
    type: 'due_diligence',
    rule: (d) => (['analysis', 'due_diligence'].includes(d.stage) ? { title: `${d.stage === 'analysis' ? 'Phân tích' : 'Thẩm định'}: ${d.name}`, priority: 'high', targetDueAt: null } : null),
  },
  'storm-plans': {
    type: 'storm',
    rule: (d) => (['inspecting', 'damaged'].includes(d.responseLevel) ? { title: `Ứng phó bão ${d.propertyCode}: ${d.responseLevel === 'damaged' ? 'có thiệt hại' : 'đang kiểm tra'}`, priority: d.responseLevel === 'damaged' ? 'urgent' : 'high', targetDueAt: null } : null),
  },
};

const sources = () => Object.keys(RULES);
const queueCfg = () => registry.get('queue-items');

/** Re-evaluates the auto item of one source record (`doc` = lean stored record). */
async function syncRecord(path, doc, { session = null, env } = {}) {
  const spec = RULES[path];
  if (!spec) return;
  const { createInternal } = require('../core/record');
  const { getEnv } = require('../core/env');
  env ||= await getEnv();
  const Q = queueCfg();
  const want = spec.rule(doc, env);
  const existing = await Q.Model.findOne({ autoGenerated: true, 'source.id': String(doc._id), type: spec.type }).session(session).lean();
  if (want && !existing) {
    await createInternal(Q, {
      type: spec.type, title: cut(want.title), priority: want.priority, targetDueAt: want.targetDueAt || null, status: 'waiting',
      autoGenerated: true, source: { resource: path, id: String(doc._id), code: doc.code },
    }, { session, env });
  } else if (want && existing.status === 'done') {
    await Q.Model.updateOne({ _id: existing._id }, { $set: { status: 'waiting', title: cut(want.title) }, $inc: { version: 1 } }, { session });
  } else if (!want && existing && existing.status !== 'done') {
    await Q.Model.updateOne({ _id: existing._id }, { $set: { status: 'done' }, $inc: { version: 1 } }, { session });
  }
}

/** Daily job: re-evaluate every source record (time-driven conditions). */
async function syncAll(env) {
  let n = 0;
  for (const path of sources()) {
    const cfg = registry.get(path);
    for await (const d of cfg.Model.find({}).lean().cursor()) {
      await syncRecord(path, d, { env });
      n++;
    }
  }
  return n;
}

module.exports = { RULES, sources, syncRecord, syncAll };
